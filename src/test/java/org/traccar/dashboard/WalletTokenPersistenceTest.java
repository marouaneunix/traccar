package org.traccar.dashboard;

import com.fasterxml.jackson.databind.ObjectMapper;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.Test;
import org.traccar.config.Config;
import org.traccar.model.Attribute;
import org.traccar.storage.DatabaseStorage;
import org.traccar.storage.query.Columns;
import org.traccar.storage.query.Condition;
import org.traccar.storage.query.Request;

import static org.junit.jupiter.api.Assertions.assertEquals;

public class WalletTokenPersistenceTest {

    @Test
    public void testExistingAttributesTableIsSufficientWithoutWalletMigration() throws Exception {
        var dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:wallet-computed-attribute;DB_CLOSE_DELAY=-1");
        try (var connection = dataSource.getConnection(); var statement = connection.createStatement()) {
            statement.execute("CREATE TABLE tc_attributes (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "description VARCHAR(4000) NOT NULL, type VARCHAR(128) NOT NULL, "
                    + "attribute VARCHAR(128) NOT NULL, expression VARCHAR(4000) NOT NULL, priority INT DEFAULT 0)");
        }
        var config = new Config();
        var storage = new DatabaseStorage(config, dataSource, new ObjectMapper());
        var attribute = new Attribute();
        attribute.setDescription("Wallet API token");
        attribute.setAttribute("wallet_token");
        attribute.setExpression("'test-only-token'");
        attribute.setType("string");
        attribute.setId(storage.addObject(attribute, new Request(new Columns.Exclude("id"))));
        assertEquals("test-only-token", new WalletTokenStore(config, storage).getToken());
        var reloaded = new DatabaseStorage(config, dataSource, new ObjectMapper());
        assertEquals("test-only-token", new WalletTokenStore(config, reloaded).getToken());
        attribute.setExpression("'replacement-token'");
        storage.updateObject(attribute, new Request(
                new Columns.Include("expression"), new Condition.Equals("id", attribute.getId())));
        assertEquals("replacement-token", new WalletTokenStore(config, reloaded).getToken());
    }
}
